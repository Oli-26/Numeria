"""Emit every Nous logo source (SVG + Android vector) from one geometry, measured off the 1024px master PNG.

Usage: python3 resources/gen-logo.py svg android   then   node resources/regen-icons.mjs
"""
import math, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAN, ORA, RUST_INK, BG = '#BFB3A2', '#C8643B', '#702F15', '#F4EFE6'
STRIPES = [  # cubic beziers in 1024 design units
    (455.9, 471.2, 485.8, 493.1, 499.8, 521.7, 455.7, 558.0),
    (491.7, 440.5, 533.7, 476.8, 547.0, 523.3, 501.8, 583.5),
    (542.7, 445.6, 567.8, 486.6, 573.5, 530.5, 547.9, 578.4),
]

def f(v): return f'{round(v, 2):g}'

class Geo:
    """Maps 1024 design units to target units: x' = s*x + tx."""
    def __init__(self, s=1.0, tx=0.0, ty=0.0, stem_top=52):
        self.s, self.tx, self.ty, self.stem_top = s, tx, ty, stem_top
    def p(self, x, y): return f(self.s * x + self.tx), f(self.s * y + self.ty)
    def w(self, v): return f(self.s * v)
    def arc(self, r, a0, a1):
        def pt(a):
            t = math.radians(a); return self.p(512 + r * math.cos(t), 512 - r * math.sin(t))
        (x0, y0), (x1, y1) = pt(a0), pt(a1)
        large = 1 if (a1 - a0) % 360 > 180 else 0
        R = self.w(r)
        return f'M{x0} {y0}A{R} {R} 0 {large} 0 {x1} {y1}'
    def rings(self):
        return [self.arc(327.5, 107.8, 432.2), self.arc(225.5, -71.9, 251.9), self.arc(127, 27.1, 332.9)]
    def path(self):
        P = self.p; R1, R2 = self.w(277), self.w(173)
        (ax, ay), (bx, by), (cx, cy), (dx, dy), (ex, ey), (gx, gy) = (
            P(512, self.stem_top), P(512, 235), P(512, 789), P(512, 685), P(685, 512), P(512, 512))
        return f'M{ax} {ay}L{bx} {by}A{R1} {R1} 0 0 0 {cx} {cy}L{dx} {dy}A{R2} {R2} 0 0 0 {ex} {ey}L{gx} {gy}'
    def ball(self):
        (x, y), r = self.p(512, 512), self.w(77.5)
        return x, y, r
    def stripes(self):
        out = []
        for b in STRIPES:
            pts = [self.p(b[i], b[i + 1]) for i in range(0, 8, 2)]
            out.append(f'M{pts[0][0]} {pts[0][1]}C{pts[1][0]} {pts[1][1]} {pts[2][0]} {pts[2][1]} {pts[3][0]} {pts[3][1]}')
        return out

def svg_logo(g, viewbox, bg=False, extra_attrs=''):
    cx, cy, r = g.ball()
    rings = ''.join(f'<path d="{d}"/>' for d in g.rings())
    stripes = ''.join(f'<path d="{d}"/>' for d in g.stripes())
    bgrect = f'<rect width="100%" height="100%" fill="{BG}"/>' if bg else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}"{extra_attrs}>{bgrect}'
            f'<g fill="none" stroke-linecap="round">'
            f'<g stroke="{TAN}" stroke-width="{g.w(56)}">{rings}</g>'
            f'<path d="{g.path()}" stroke="{ORA}" stroke-width="{g.w(60)}" stroke-linejoin="round"/>'
            f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{ORA}"/>'
            f'<g stroke="{RUST_INK}" stroke-opacity=".45" stroke-width="{g.w(14.4)}">{stripes}</g>'
            f'</g></svg>\n')

def vector_logo(g, size, mono, comment):
    """Android VectorDrawable. mono: white, tan rings at partial alpha so they stay distinct from the path."""
    cx, cy, r = g.ball()
    tan, ora = ('#FFFFFFFF', '#FFFFFFFF') if mono else ('#FF' + TAN[1:], '#FF' + ORA[1:])
    tan_alpha = ' android:strokeAlpha="0.5"' if mono else ''
    rings = ''.join(
        f'\n    <path android:pathData="{d}" android:strokeColor="{tan}"{tan_alpha} '
        f'android:strokeWidth="{g.w(56)}" android:strokeLineCap="round" />' for d in g.rings())
    ball = f'M{f(float(cx) - float(r))},{cy}a{r},{r} 0 1,0 {f(2 * float(r))},0a{r},{r} 0 1,0 -{f(2 * float(r))},0Z'
    stripes = '' if mono else ''.join(
        f'\n    <path android:pathData="{d}" android:strokeColor="#FF{RUST_INK[1:]}" android:strokeAlpha="0.45" '
        f'android:strokeWidth="{g.w(14.4)}" android:strokeLineCap="round" />' for d in g.stripes())
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by resources/gen-logo.py. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">{rings}\n'
            f'    <path android:pathData="{g.path()}" android:strokeColor="{ora}" android:strokeWidth="{g.w(60)}"\n'
            f'        android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
            f'    <path android:pathData="{ball}" android:fillColor="{ora}" />{stripes}\n'
            f'</vector>\n')

def write(rel, text):
    with open(f'{ROOT}/{rel}', 'w') as fh: fh.write(text)
    print('wrote', rel, len(text))

full = Geo()                       # 1024 store/legacy framing, full stem
# Adaptive framing (matches the supplied 432px foreground): rings centred, stem shortened to stay in the safe circle.
S108 = 0.2841 * 108 / 432
adaptive = Geo(S108, 54 - 512 * S108, 54 - 512 * S108, stem_top=86)
S24 = 22 / 846
notif = Geo(S24, 12 - 512 * S24, 1 - 22 * S24)

if 'svg' in sys.argv:
    write('resources/icon-only.svg', svg_logo(full, '0 0 1024 1024', bg=True))
    write('resources/icon-foreground.svg', svg_logo(adaptive, '0 0 108 108'))
    write('resources/icon-background.svg', f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" fill="{BG}"/></svg>\n')
    write('wwwroot/nous-icon.svg', svg_logo(full, '0 0 1024 1024', bg=True))
    write('wwwroot/nous-mark.svg', svg_logo(full, '156 22 712 846'))
if 'android' in sys.argv:
    write('android/app/src/main/res/drawable/ic_launcher_monochrome.xml', vector_logo(adaptive, 108, True, 'Themed-icon layer (Android 13+).'))
    write('android/app/src/main/res/drawable/ic_stat_nous.xml', vector_logo(notif, 24, True, 'Notification small icon.'))
    write('android/app/src/main/res/drawable/splash_icon.xml', vector_logo(adaptive, 108, False, 'Splash mark for API 24-25.'))
